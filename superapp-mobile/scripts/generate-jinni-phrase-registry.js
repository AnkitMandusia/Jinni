#!/usr/bin/env node
/**
 * Regenerates src/modules/jinni/services/audio/phraseRegistry.generated.ts
 * from phraseAudioMap.json + whatever WAV files actually exist under
 * assets/audio/jinni/hi-IN/.
 *
 * Why this exists (Prompt.txt section A, requirement 5): React Native /
 * Metro needs every `require('./some.wav')` call to be a *static*,
 * literal string at bundle time — you cannot `require(dynamicPath)` or
 * try/catch a missing asset at runtime the way you could on a server.
 * So the registry can't "scan the folder" from inside the app itself;
 * instead this script does that scan ahead of time, on your machine,
 * and writes out only the require() lines for files that are really
 * there. Anything listed in phraseAudioMap.json but not yet recorded
 * is simply left out — the app's audioPlayer already treats a missing
 * entry as "skip playback safely" (requirement 4), so nothing crashes.
 *
 * A phraseKey can map to MULTIPLE files (array, possibly across several
 * entries in phraseAudioMap.json, which this script merges) —
 * phraseRegistry picks one at random each time that phrase plays, so a
 * frequently-repeated line (e.g. "thinking", heard on every wish)
 * doesn't sound identical every time.
 *
 * Usage:
 *   node scripts/generate-jinni-phrase-registry.js
 *
 * Run it again any time you add/replace WAV files or edit
 * phraseAudioMap.json.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const AUDIO_ROOT = path.join(ROOT, 'assets', 'audio', 'jinni', 'hi-IN');
const MAP_PATH = path.join(
  ROOT,
  'src/modules/jinni/services/audio/phraseAudioMap.json'
);
const OUT_TS = path.join(
  ROOT,
  'src/modules/jinni/services/audio/phraseRegistry.generated.ts'
);
const OUT_INVENTORY = path.join(ROOT, 'JINNI_AUDIO_INVENTORY.generated.md');

function readMap() {
  if (!fs.existsSync(MAP_PATH)) {
    console.error(`Missing ${MAP_PATH}`);
    process.exit(1);
  }
  const raw = JSON.parse(fs.readFileSync(MAP_PATH, 'utf8'));
  return raw.entries || [];
}

function scanActualFiles() {
  /** @type {Record<string, string[]>} folder -> filenames that exist on disk */
  const found = {};
  if (!fs.existsSync(AUDIO_ROOT)) return found;
  for (const folder of fs.readdirSync(AUDIO_ROOT)) {
    const dir = path.join(AUDIO_ROOT, folder);
    if (!fs.statSync(dir).isDirectory()) continue;
    found[folder] = fs.readdirSync(dir).filter((f) => f.toLowerCase().endsWith('.wav'));
  }
  return found;
}

function main() {
  const entries = readMap();
  const onDisk = scanActualFiles();

  /** @type {Map<string, Array<{folder: string, file: string}>>} phraseKey -> registered (folder,file) pairs */
  const registeredByKey = new Map();
  const missing = [];

  for (const entry of entries) {
    const { phraseKey, folder } = entry;
    const files = entry.files || (entry.file ? [entry.file] : []);
    if (!folder || !phraseKey || files.length === 0) continue;
    for (const file of files) {
      const exists = (onDisk[folder] || []).includes(file);
      if (exists) {
        if (!registeredByKey.has(phraseKey)) registeredByKey.set(phraseKey, []);
        registeredByKey.get(phraseKey).push({ folder, file });
      } else {
        missing.push({ phraseKey, folder, file });
      }
    }
  }

  // Anything physically present but not referenced by any phraseKey entry.
  const allMappedPairs = new Set();
  for (const entry of entries) {
    const files = entry.files || (entry.file ? [entry.file] : []);
    for (const file of files) allMappedPairs.add(`${entry.folder}/${file}`);
  }
  const unmapped = [];
  for (const [folder, files] of Object.entries(onDisk)) {
    for (const file of files) {
      if (!allMappedPairs.has(`${folder}/${file}`)) unmapped.push({ folder, file });
    }
  }

  const lines = [];
  lines.push('/**');
  lines.push(' * AUTO-GENERATED by scripts/generate-jinni-phrase-registry.js');
  lines.push(' * Do not hand-edit — edit phraseAudioMap.json and re-run the script.');
  lines.push(` * Generated: ${new Date().toISOString()}`);
  lines.push(' */');
  lines.push("import type { PhraseKey } from '../jinniPhrases';");
  lines.push('');

  const keys = Array.from(registeredByKey.keys());
  if (keys.length === 0) {
    lines.push(
      '// No WAV files were found under assets/audio/jinni/hi-IN/ matching'
    );
    lines.push(
      '// phraseAudioMap.json yet. The registry is intentionally empty —'
    );
    lines.push(
      '// speakJinniPhrase() falls back to on-device TTS for every phrase'
    );
    lines.push('// until you record audio and re-run this script.');
    lines.push('');
  }

  let i = 0;
  const varNamesByKey = new Map();
  for (const key of keys) {
    const pairs = registeredByKey.get(key);
    const varNames = pairs.map((p) => {
      const v = `audio_${i++}`;
      lines.push(
        `const ${v} = require('../../../../../assets/audio/jinni/hi-IN/${p.folder}/${p.file}');`
      );
      return v;
    });
    varNamesByKey.set(key, varNames);
  }
  lines.push('');
  lines.push(
    '// One or more bundled clips per phrase — speakJinniPhrase/audioPlayer pick one at random each play.'
  );
  lines.push('export const PHRASE_AUDIO_REGISTRY: Partial<Record<PhraseKey, number[]>> = {');
  for (const key of keys) {
    lines.push(`  ${key}: [${varNamesByKey.get(key).join(', ')}],`);
  }
  lines.push('};');
  lines.push('');
  lines.push('export default PHRASE_AUDIO_REGISTRY;');
  lines.push('');

  fs.writeFileSync(OUT_TS, lines.join('\n'), 'utf8');

  const inv = [];
  inv.push('# Jinni audio inventory (auto-generated)');
  inv.push('');
  inv.push(`Generated: ${new Date().toISOString()}`);
  inv.push('');
  inv.push(`## Registered (${keys.length} phrase key(s)) — bundled and playable`);
  for (const key of keys) {
    const pairs = registeredByKey.get(key);
    inv.push(`- ${key} -> ${pairs.map((p) => `${p.folder}/${p.file}`).join(', ')}`);
  }
  inv.push('');
  inv.push(`## Missing (${missing.length}) — mapped in phraseAudioMap.json but no WAV found yet`);
  inv.push('(speakJinniPhrase() falls back to on-device TTS for these)');
  for (const m of missing) inv.push(`- ${m.phraseKey} -> ${m.folder}/${m.file}`);
  inv.push('');
  inv.push(`## Unmapped files (${unmapped.length}) — WAV exists but no phraseKey points at it`);
  for (const u of unmapped) inv.push(`- ${u.folder}/${u.file}`);
  inv.push('');
  fs.writeFileSync(OUT_INVENTORY, inv.join('\n'), 'utf8');

  console.log(`Registered ${keys.length} phrase key(s), ${missing.length} still missing, ${unmapped.length} unmapped file(s).`);
  console.log(`Wrote ${path.relative(ROOT, OUT_TS)}`);
  console.log(`Wrote ${path.relative(ROOT, OUT_INVENTORY)}`);
}

main();
